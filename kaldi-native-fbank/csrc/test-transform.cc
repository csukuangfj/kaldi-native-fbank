TEST(FeatureTransform, HandCaseLinear) {
  // y = x M^T with M = [[1 2 3], [4 5 6]] (2x3): x = [1 0 1] -> [4, 10].
  MatrixF mat(2, 3);
  mat << 1, 2, 3, 4, 5, 6;
  FeatureTransform t(mat);

  MatrixF feats(1, 3);
  feats << 1, 0, 1;
  MatrixF out = t.Apply(feats);
  ASSERT_EQ(out.rows(), 1);
  ASSERT_EQ(out.cols(), 2);
  EXPECT_FLOAT_EQ(out(0, 0), 4.0f);
  EXPECT_FLOAT_EQ(out(0, 1), 10.0f);
  EXPECT_FALSE(t.IsAffine(3));
  EXPECT_EQ(t.InputDim(), 3);
  EXPECT_EQ(t.OutputDim(), 2);
}

TEST(FeatureTransform, HandCaseAffine) {
  // 2x4 transform on 3-dim input: last column is the offset.
  MatrixF mat(2, 4);
  mat << 1, 2, 3, 0.5f, 4, 5, 6, -1.5f;
  FeatureTransform t(mat);
  EXPECT_TRUE(t.IsAffine(3));

  MatrixF feats(1, 3);
  feats << 1, 0, 1;
  MatrixF out = t.Apply(feats);
  // y = [1,0,1] . [[1,2,3],[4,5,6]]^T + [0.5, -1.5] = [4.5, 8.5]
  EXPECT_FLOAT_EQ(out(0, 0), 4.5f);
  EXPECT_FLOAT_EQ(out(0, 1), 8.5f);
}

TEST(FeatureTransform, SingleFrameMatchesMatrix) {
  MatrixD feats;
  ASSERT_TRUE(LoadNpy(GoldenDir() + "/golden/aishell3_typical/spliced.utt.npy",
                      &feats));
  MatrixF feats_f = feats.cast<float>();
  FeatureTransform lda =
      FeatureTransform::Read(GoldenDir() + "/lda_test_91.mat");

  MatrixF out = lda.Apply(feats_f);
  std::vector<float> frame(lda.OutputDim());
  for (int32_t r = 0; r < feats_f.rows(); ++r) {
    lda.Apply(feats_f.row(r).data(), feats_f.cols(), frame.data());
    for (int32_t c = 0; c < lda.OutputDim(); ++c) {
      // The matrix and single-frame paths accumulate in different orders;
      // compare with a relative tolerance.
      EXPECT_LE(std::fabs(out(r, c) - frame[c]),
                1e-5 * (1.0 + std::fabs(out(r, c))));
    }
  }
}

TEST(FeatureTransform, Errors) {
  FeatureTransform lda =
      FeatureTransform::Read(GoldenDir() + "/lda_test_91.mat");
  MatrixF bad(2, 7);  // neither 91 nor 90 columns
  bad.setZero();
  EXPECT_THROW(lda.Apply(bad), std::invalid_argument);
  EXPECT_THROW(FeatureTransform::Read(GoldenDir() + "/no_such_file.mat"),
               std::runtime_error);
}


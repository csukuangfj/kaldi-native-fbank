TEST(FeatureTransform, ReadMatchesNpy) {
  // The golden .mat must hold exactly the same values as the golden .npy
  // (both generated by tests/data/feat_golden/generate.sh).
  FeatureTransform t91 =
      FeatureTransform::Read(GoldenDir() + "/lda_test_91.mat");
  MatrixD ref;
  ASSERT_TRUE(LoadNpy(GoldenDir() + "/lda_test_91.npy", &ref));
  ASSERT_EQ(t91.OutputDim(), ref.rows());
  ASSERT_EQ(t91.InputDim(), ref.cols());

  // The transform applied to the identity is the matrix itself; the
  // reader must reproduce the golden .npy exactly.
  MatrixF eye = MatrixF::Identity(ref.cols(), ref.cols());
  MatrixF out = t91.Apply(eye);
  MatrixD ref_t = ref.transpose();
  EXPECT_LT(MaxAbsDiff(out, ref_t), 1e-5);
}


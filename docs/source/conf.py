def get_version():
    cmake_file = "../../CMakeLists.txt"
    with open(cmake_file) as f:
        content = f.read()

    version = re.search(r"set\(KALDI_NATIVE_FBANK_VERSION (.*)\)", content).group(1)
    return version.strip('"')


